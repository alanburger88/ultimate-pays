function historySection(ctx, m) {
  const t = ctx.t;
  if (!m.history.length) return null;
  return h('section', { class: 'pl-px-section' },
    h('h2', null, t('record.history_title')),
    h('p', null, t('record.history_desc')),
    h('table', { class: 'pl-px-table' },
      h('thead', null, h('tr', null,
        h('th', { scope: 'col' }, t('export.col_period')), h('th', { scope: 'col' }, t('export.col_pay_date')),
        h('th', { scope: 'col' }, t('export.col_tax_year')), h('th', { scope: 'col', class: 'num' }, t('export.col_lines')),
        h('th', { scope: 'col', class: 'num' }, m.history[0].netLabel),
      )),
      h('tbody', null, m.history.map((p) => h('tr', { dataset: { period: p.periodId } },
        h('td', null, p.periodText), h('td', null, p.payDateText || '—'), h('td', null, p.taxYearLabel || '—'),
        h('td', { class: 'num' }, ctx.fmt.number(p.count)), h('td', { class: 'num' }, amount(ctx, p.netMinor)),
      ))),
    ),
  );
}

/**
 * The complete record as a print document. Returned element is appended to
 * #pl-print-host by the shell on `beforeprint`; exports.css shows it only in
 * print media. Paper size follows the profile via an injected @page rule.
 */
export function buildPrintView(ctx) {
  const t = ctx.t;
  const m = recordModel(ctx);
  const paper = String(ctx.doc.profile.paper || 'a4').toLowerCase() === 'letter' ? 'Letter' : 'A4';
  const footerLine = m.footer;
  return h('div', { class: 'pl-px', lang: ctx.locale, dataset: { paper: paper.toLowerCase() } },
    h('style', null, `@page { size: ${paper}; margin: 16mm 14mm; }`),
    h('header', { class: 'pl-px-head' },
      h('h1', null, m.header),
      h('p', { class: 'pl-px-meta' }, [m.employerName, m.employeeName, m.recordId, m.versionText, m.language].filter(Boolean).join(' · ')),
      m.constructed ? h('p', { class: 'pl-px-notice' }, t('export.notice_constructed')) : null,
    ),
    h('section', { class: 'pl-px-section' },
      h('h2', null, t('record.particulars')),
      h('div', { class: 'pl-px-groups' }, dlGroup(ctx, m.particulars.employer), dlGroup(ctx, m.particulars.employee), dlGroup(ctx, m.particulars.document), dlGroup(ctx, m.particulars.payment)),
    ),
    h('section', { class: 'pl-px-section' },
      h('h2', null, t('record.full_record')),
      m.categories.map((cat) => linesTable(ctx, cat)),
      totalsTable(ctx, m),
    ),
    timeSection(ctx, m),
    h('section', { class: 'pl-px-section' },
      h('h2', null, t('record.disclosures')),
      h('ul', { class: 'pl-px-list' }, m.disclosures.map((x) => h('li', { dataset: { key: x.key } }, x.text, x.required ? h('span', { class: 'pl-px-req' }, ` [${t('common.required')}]`) : null))),
    ),
    m.policies.length ? h('section', { class: 'pl-px-section' },
      h('h2', null, t('record.policies')),
      h('ul', { class: 'pl-px-list' }, m.policies.map((p) => h('li', { dataset: { policy: p.id } }, p.title))),
    ) : null,
    h('section', { class: 'pl-px-section' },
      h('h2', null, t('record.provenance')),
      h('ul', { class: 'pl-px-list' }, m.provenance.map((x) => h('li', null, x))),
      h('h3', null, t('record.version_lineage')),
      h('ul', { class: 'pl-px-list' }, m.lineage.map((x) => h('li', null, x))),
    ),
    historySection(ctx, m),
    h('section', { class: 'pl-px-section pl-px-notices' },
      m.notices.map((x) => h('p', { class: 'pl-px-notice' }, x)),
      h('p', { class: 'pl-px-meta' }, `${t('export.language')}: ${m.language} · ${t('export.generated', { date: m.generatedText })}`),
    ),
    h('footer', { class: 'pl-px-foot' }, h('p', null, footerLine)),
  );
}
