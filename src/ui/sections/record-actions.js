function dl(rows) {
  return h('dl', { class: 'pl-dl' }, rows.filter(Boolean).map(([k, v]) => [h('dt', null, k), h('dd', null, v)]));
}

function group(title, iconName, rows, extra = null) {
  const hid = uid('rag');
  return h('section', { class: 'pl-ra-group', aria: { labelledby: hid } }, h('h3', { id: hid }, icon(iconName, { size: 16 }), h('span', null, title)), dl(rows), extra);
}

function sub(text) { return text ? h('span', { class: 'sub' }, text) : null; }

function employerGroup(ctx) {
  const t = ctx.t;
  const { employer } = ctx.doc.record;
  const { profile, content } = ctx.doc;
  if (!employer) return null;
  const a = employer.address || null;
  const country = a && a.country ? (profile.countryKey && a.country === profile.country && has(profile.countryKey) ? t(profile.countryKey) : a.country) : null;
  const addr = a ? [...(a.lines || []), [a.city, a.region, a.postalCode].filter(Boolean).join(' '), country].filter(Boolean) : [];
  const contact = employer.payrollContact || null;
  return group(t('record.employer_particulars'), 'building', [
    employer.legalName ? [t('record.field_legal_name'), employer.legalName] : null,
    employer.tradingName && employer.tradingName !== employer.legalName ? [t('record.field_trading_name'), employer.tradingName] : null,
    addr.length ? [t('record.field_address'), addr.map((line, i) => [i ? h('br') : null, line])] : null,
    ...(employer.registrations || []).map((r) => [content.employerField(r.key), h('span', { class: 'tabular' }, r.valueMasked)]),
    contact ? [t('record.field_payroll_contact'), [contact.label || null, contact.email ? [contact.label ? h('br') : null, h('a', { href: `mailto:${contact.email}` }, contact.email)] : null, contact.phone ? [h('br'), contact.phone] : null]] : null,
  ]);
}

function employeeGroup(ctx) {
  const t = ctx.t;
  const { employee } = ctx.doc.record;
  const { content } = ctx.doc;
  if (!employee) return null;
  // Governed field labels where the content pack has them; interface labels otherwise.
  const f = (key, fallbackKey) => { const v = content.employeeField(key); return v && v !== key ? v : t(fallbackKey); };
  const ids = employee.identifiers || [];
  return group(t('record.employee_particulars'), 'user', [
    [t('common.name'), employee.displayName],
    employee.employeeNumber ? [f('employeeNumber', 'record.field_employee_number'), h('span', { class: 'tabular' }, employee.employeeNumber)] : null,
    employee.occupation ? [f('occupation', 'record.field_occupation'), employee.occupation] : null,
    employee.classification ? [f('classification', 'record.field_classification'), employee.classification] : null,
    employee.department ? [f('department', 'record.field_department'), employee.department] : null,
    employee.location ? [f('location', 'record.field_location'), employee.location] : null,
    employee.hireDate ? [f('hireDate', 'record.field_hire_date'), ctx.fmt.date(employee.hireDate)] : null,
    ...ids.map((r) => [content.employeeField(r.key), h('span', { class: 'tabular' }, r.valueMasked)]),
  ], ids.length ? h('p', { class: 'pl-hint' }, t('record.masked_note')) : null);
}

function documentGroup(ctx) {
  const t = ctx.t;
  const { record, profile, content } = ctx.doc;
  const d = record.document;
  const period = d.period || {};
  const freq = period.frequency || profile.payFrequency || null;
  const langs = (d.languages || []).map((l) => LANGUAGE_NAMES[l] || l).join(', ');
  const kind = content.document('recordKind');
  const title = content.document('title');
  const basis = profile.taxYear && profile.taxYear.basisKey && has(profile.taxYear.basisKey) ? t(profile.taxYear.basisKey) : null;
  return group(t('record.document_particulars'), 'file', [
    [t('masthead.reference'), h('span', { class: 'tabular break' }, d.id)],
    [t('record.field_version'), String(d.version)],
    kind || title ? [t('record.field_document_kind'), kind && title && kind !== title ? [title, sub(kind)] : (kind || title)] : null,
    d.issuedAt ? [t('record.field_issued'), ctx.fmt.dateTime(d.issuedAt)] : null,
    period.start && period.end ? [t('masthead.period'), [ctx.fmt.period(period), period.sequence && period.of ? sub(t('masthead.period_of', { sequence: period.sequence, of: period.of })) : null]] : null,
    d.payDate ? [t('masthead.pay_date'), ctx.fmt.date(d.payDate)] : null,
    d.currency ? [t('masthead.currency'), d.currency] : null,
    d.taxYear ? [t('record.field_tax_year'), [d.taxYear.label, sub([basis, d.taxYear.start && d.taxYear.end ? `${basis ? ' · ' : ''}${ctx.fmt.period({ start: d.taxYear.start, end: d.taxYear.end })}` : null].filter(Boolean).join(''))]] : null,
    freq ? [t('record.field_pay_frequency'), has(`record.frequency_${freq}`) ? t(`record.frequency_${freq}`) : freq] : null,
    [t('record.field_profile_version'), `${d.profileId || profile.id} · ${t('masthead.version', { version: d.profileVersion || profile.version })}`],
    d.contentVersion ? [t('record.field_content_version'), String(d.contentVersion)] : null,
    langs ? [t('record.field_languages'), langs] : null,
  ]);
}

function paymentGroup(ctx) {
  const t = ctx.t;
  const { record, content } = ctx.doc;
  const p = record.payment;
  if (!p) return null;
  return group(t('record.payment_particulars'), 'wallet', [
    p.method ? [t('record.field_payment_method'), content.paymentMethod(p.method)] : null,
    p.bankMasked ? [t('record.field_bank'), h('span', { class: 'tabular break' }, p.bankMasked)] : null,
    typeof p.amountMinor === 'number' ? [t('common.amount'), amount(ctx, p.amountMinor, { cls: 'strong' })] : null,
    p.date ? [t('masthead.pay_date'), ctx.fmt.date(p.date)] : null,
    p.reference ? [t('record.field_payment_reference'), h('span', { class: 'tabular break' }, p.reference)] : null,
  ]);
}

// --- every line ----------------------------------------------------------------

function orderedLines(ctx) {
  const { record, profile } = ctx.doc;
  const order = [...(profile.categoryOrder || [])];
  for (const l of record.lines) if (!order.includes(l.category)) order.push(l.category);
  return record.lines.map((line, idx) => ({ line, idx }))
    .sort((a, b) => (order.indexOf(a.line.category) - order.indexOf(b.line.category)) || (a.idx - b.idx))
    .map((x) => x.line);
}

function linesBlock(ctx, narrow) {
  const t = ctx.t;
  const lines = orderedLines(ctx);
  const selected = new Set(ctx.store.get().selection.lineIds || []);
  const hid = uid('ralines');
  return h('section', { class: 'pl-ra-lines pl-ra-panel', aria: { labelledby: hid } },
    h('div', { class: 'row-between' }, h('h3', { id: hid }, t('record.lines_title')), h('span', { class: 'muted small' }, t('common.lines', { count: lines.length }))),
    h('p', { class: 'muted small pl-ra-lines-desc' }, t('record.lines_desc')),
    narrow ? h('div', { class: 'pl-cards' }, lines.map((l) => lineCard(ctx, l, selected.has(l.id)))) : linesTable(ctx, lines, selected),
    totalsList(ctx),
  );
}

function selectBox(ctx, line, isSelected) {
  const label = ctx.content.lineLabel(line);
  return h('input', {
    type: 'checkbox', class: 'pl-rowcheck', checked: isSelected,
    aria: { label: `${ctx.t('details.col_select')}: ${label}` },
    dataset: { lineFocus: '', focusKey: `ra-sel-${line.id}` },
    on: { change: () => ctx.actions.toggleSelect(line.id) },
  });
}

function openLineButton(ctx, line, { text = false } = {}) {
  const label = ctx.content.lineLabel(line);
  return h('button', {
    class: ['pl-btn pl-btn-sm', !text && 'pl-btn-quiet pl-btn-icon'], type: 'button',
    dataset: { focusKey: `ra-open-${line.id}` }, aria: { label: ctx.t('record.open_line', { line: label }) }, title: text ? null : ctx.t('common.go_to_line'),
    on: { click: () => ctx.actions.focusLine(line.id) },
  }, icon('forward', { size: 16 }), text ? h('span', null, ctx.t('common.go_to_line')) : null);
}

