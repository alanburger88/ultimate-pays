function privacyCard(ctx) {
  const t = ctx.t;
  const s = ctx.store.get();
  const retain = Boolean(s.retainDrafts);
  const sel = s.selection || {};
  const q = s.queries || {};
  const counts = [[Object.keys(sel.tags || {}).length, 'record.local_tags'], [Object.keys(sel.notes || {}).length, 'record.local_notes'], [(q.drafts || []).length, 'record.local_drafts']];
  const noteId = 'ra-keep-note';
  const stateId = 'ra-keep-state';
  const input = h('input', { type: 'checkbox', role: 'switch', checked: retain, aria: { checked: String(retain), describedby: `${stateId} ${noteId}` }, dataset: { focusKey: 'ra-retain' } });
  const stateEl = h('p', { class: 'muted small', id: stateId }, t(retain ? 'record.stored_browser' : 'record.stored_session'));
  input.addEventListener('change', () => {
    const on = input.checked;
    ctx.actions.setRetainDrafts(on);
    input.setAttribute('aria-checked', String(on));
    stateEl.textContent = t(on ? 'record.stored_browser' : 'record.stored_session');
    announce(t(on ? 'record.keep_drafts_on' : 'record.keep_drafts_off'));
  });
  return [
    h('p', { class: 'small' }, t('record.privacy_local_desc')),
    h('ul', { class: 'pl-ra-stored', aria: { label: t('common.local_only') } }, counts.map(([n, key]) => h('li', { class: 'pl-chip' }, t(key, { count: n })))),
    h('div', { class: 'pl-btn-group' }, h('button', { class: 'pl-btn pl-btn-danger', type: 'button', dataset: { focusKey: 'ra-clear' }, on: { click: () => clearLocal(ctx) } }, icon('trash', { size: 16 }), h('span', null, t('record.clear_local')))),
    h('div', { class: 'pl-ra-keep' },
      h('label', { class: 'pl-switch pl-ra-switch' }, input, h('span', { class: 'track', aria: { hidden: 'true' } }), h('span', { class: 'txt' }, t('record.keep_drafts'))),
      stateEl,
      h('p', { class: 'pl-hint', id: noteId }, t('record.keep_drafts_note')),
    ),
  ];
}

async function clearLocal(ctx) {
  const t = ctx.t;
  const ok = await confirmDialog({ title: t('record.clear_local'), body: t('record.clear_local_confirm'), confirmLabel: t('record.delete'), cancelLabel: t('common.cancel'), danger: true });
  if (!ok) return;
  ctx.actions.clearLocal();
  announce(t('record.cleared'));
}
