export function render(ctx) {
  liveCtx = ctx;
  const t = ctx.t;
  const narrow = useCards(ctx);
  const modules = ctx.modules();
  if (!narrow) {
    // Long translations can make the listing wider than the page; measure after layout and fall back to cards.
    requestAnimationFrame(() => {
      const over = Array.from(document.querySelectorAll('#pl-section-host .pl-ra-table')).some((tbl) => tbl.parentElement && tbl.scrollWidth > tbl.parentElement.clientWidth + 1);
      if (over && liveCtx === ctx && ctx.store.get().nav.section === 'record-actions') { tooWide.add(fitKey(ctx)); ctx.store.update('nav', (n) => ({ ...n })); }
    });
  }
  const parts = [
    { id: 'full', title: t('record.full_record'), icon: 'file', build: fullRecordCard },
    { id: 'provenance', title: t('record.provenance'), icon: 'shield', build: provenanceCard },
    { id: 'keep', title: t('record.retain_title'), icon: 'download', build: keepCard },
    modules.queries ? { id: 'actions', title: t('record.actions_title'), icon: 'send', build: actionsCard } : null,
    modules.wallet ? { id: 'wallet', title: t('record.wallet_title'), icon: 'wallet', build: walletCard } : null,
    { id: 'privacy', title: t('record.privacy_local'), icon: 'lock', build: privacyCard },
  ].filter(Boolean);

  return h('div', { class: 'stack-lg pl-ra' },
    sectionHeader(ctx, t('record.title'), t('record.intro')),
    jumpNav(ctx, parts),
    parts.map((p) => card(p, p.build(ctx, { narrow }))),
  );
}

function card(part, body) {
  const hid = `ra-h-${part.id}`;
  return h('section', { class: 'pl-card pl-card-lg pl-ra-card stack', id: `ra-${part.id}`, aria: { labelledby: hid }, dataset: { part: part.id } },
    h('h2', { id: hid, tabindex: '-1' }, icon(part.icon, { size: 20 }), h('span', null, part.title)),
    body,
  );
}

function jumpNav(ctx, parts) {
  const t = ctx.t;
  return h('nav', { class: 'pl-ra-jump', aria: { label: t('record.jump_label') } },
    h('span', { class: 'muted small lbl' }, t('record.jump_label')),
    parts.map((p) => h('button', { class: 'pl-ra-jump-btn', type: 'button', dataset: { focusKey: `ra-jump-${p.id}` }, on: { click: () => jumpTo(ctx, p.id) } }, p.title)),
  );
}

function jumpTo(ctx, id) {
  const sec = document.getElementById(`ra-${id}`);
  if (!sec) return;
  sec.scrollIntoView({ block: 'start', behavior: ctx.reducedMotion() ? 'auto' : 'smooth' });
  const head = document.getElementById(`ra-h-${id}`);
  if (head) head.focus({ preventScroll: true });
}

