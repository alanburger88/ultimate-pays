const INTEGRITY_CHIP = {
  checking: ['pl-chip-info', 'record.integrity_chip_checking'],
  verified: ['pl-chip-positive', 'record.integrity_chip_verified'],
  failed: ['pl-chip-negative', 'record.integrity_chip_failed'],
};

/** Integrity panel body. "Verified" only ever comes from a real service result stored for this document. */
function integrityBody(ctx) {
  const t = ctx.t;
  const { record } = ctx.doc;
  const service = ctx.services && ctx.services.verification;
  const connected = Boolean(service && service.connected);
  const st = verifyState.get(ctx.scope) || { status: 'idle' };
  const [chipCls, chipKey] = INTEGRITY_CHIP[st.status] || ['pl-chip-warn', 'record.integrity_chip_not_verified'];
  const declared = record.document.integrity || {};
  const serviceName = (service && service.name) || '—';
  const body = [
    h('div', { class: 'pl-ra-status', tabindex: '-1' }, h('span', { class: ['pl-chip', chipCls], dataset: { integrity: st.status } }, t(chipKey)), declared.method ? h('span', { class: 'muted xs' }, t('record.integrity_method', { method: declared.method })) : null),
  ];
  if (!connected) {
    body.push(notice(ctx, t('record.integrity_not_verified'), { kind: 'neutral' }));
    body.push(h('p', { class: 'muted small' }, t('record.integrity_unavailable')));
    return body;
  }
  body.push(h('p', { class: 'muted small' }, t('record.integrity_service', { service: serviceName })));
  if (st.status === 'checking') body.push(h('p', { role: 'status', class: 'small' }, t('record.integrity_checking', { service: serviceName })));
  else if (st.status === 'verified') body.push(notice(ctx, st.at ? t('record.integrity_verified', { service: st.service || serviceName, date: ctx.fmt.dateTime(st.at) }) : t('record.integrity_verified_nodate', { service: st.service || serviceName }), { kind: 'success' }));
  else if (st.status === 'failed') body.push(notice(ctx, [h('p', { class: 'strong' }, t('record.integrity_failed')), st.reason ? h('p', { class: 'muted small' }, t('record.integrity_reason', { code: st.reason })) : null], { kind: 'error' }));
  else if (st.status === 'unavailable') body.push(notice(ctx, [h('p', null, t('record.integrity_unavailable')), st.reason ? h('p', { class: 'muted small' }, t('record.integrity_reason', { code: st.reason })) : null], { kind: 'warn' }));
  else body.push(notice(ctx, t('record.integrity_not_checked', { service: serviceName }), { kind: 'neutral' }));
  const busy = st.status === 'checking';
  body.push(h('div', { class: 'pl-btn-group' },
    h('button', { class: 'pl-btn pl-btn-primary', type: 'button', disabled: busy, aria: { busy: String(busy) }, dataset: { focusKey: 'ra-verify' }, on: { click: () => runVerification(ctx) } },
      icon('shield', { size: 16 }), t(st.status === 'failed' || st.status === 'unavailable' ? 'common.retry' : 'record.integrity_verify'))));
  return body;
}

async function runVerification(ctx) {
  const t = ctx.t;
  const service = ctx.services.verification;
  const scope = ctx.scope;
  const serviceName = service.name || '—';
  const pressed = activeFocusKey();
  verifyState.set(scope, { status: 'checking' });
  refreshIntegrity(ctx);
  announce(t('record.integrity_checking', { service: serviceName }));
  let result;
  // A thrown error means no check happened; only the service's explicit answer can be 'failed'.
  try { result = await service.verify(ctx.doc.record); } catch (err) { result = { status: 'unavailable', reason: 'network' }; }
  const r = result || {};
  const next = r.status === 'verified'
    ? { status: 'verified', service: r.service || serviceName, at: r.at || null }
    : r.status === 'failed' ? { status: 'failed', reason: r.reason || 'not_confirmed' }
      : { status: 'unavailable', reason: r.reason || null };
  verifyState.set(scope, next);
  refreshIntegrity(ctx, pressed);
  const msg = next.status === 'verified' ? (next.at ? t('record.integrity_verified', { service: next.service, date: ctx.fmt.dateTime(next.at) }) : t('record.integrity_verified_nodate', { service: next.service }))
    : next.status === 'unavailable' ? t('record.integrity_unavailable') : t('record.integrity_failed');
  announce(msg, { assertive: next.status !== 'verified' });
}

function activeFocusKey() {
  const a = document.activeElement;
  return a && a.dataset ? a.dataset.focusKey || null : null;
}

/**
 * Re-render a panel in place after an async service result. Keyboard focus that was inside the
 * panel is put back on the same control, or on the panel's status row while that control is
 * disabled or gone, so it never falls to <body>.
 */
function refreshPanel(host, build, fallbackSelector, preferKey = null) {
  const active = document.activeElement;
  const inside = Boolean(active && host.contains(active));
  const key = inside ? preferKey || active.dataset.focusKey || null : null;
  replaceChildren(host, build());
  if (!inside) return;
  const again = key ? host.querySelector(`[data-focus-key="${key}"]`) : null;
  const target = again && !again.disabled ? again : host.querySelector(fallbackSelector);
  if (target) target.focus({ preventScroll: true });
}

function refreshIntegrity(ctx, preferKey = null) {
  const host = document.getElementById('ra-integrity-panel');
  if (host) refreshPanel(host, () => integrityBody(ctx), '.pl-ra-status', preferKey);
}

function lineLabelById(ctx, id) {
  const l = ctx.line(id) || (ctx.doc.record.history || []).flatMap((p) => p.lines || []).find((x) => x.id === id) || null;
  return l ? ctx.content.lineLabel(l) : id;
}

/** Arithmetic consistency from calc.verifyRecord: truthful, and explicitly not tamper evidence. */
function consistencyBody(ctx) {
  const t = ctx.t;
  const { computed, content } = ctx.doc;
  const v = computed.verify || null;
  const issues = [];
  if (v) {
    for (const m of (v.totals && v.totals.mismatches) || []) {
      issues.push(m.supplied === null
        ? t('record.issue_total_missing', { total: content.total(m.id) })
        : h('span', null, t('record.issue_total', { total: content.total(m.id) }), ' (', amount(ctx, m.computed), ' ≠ ', amount(ctx, m.supplied), ').'));
    }
    for (const p of v.lineProblems || []) issues.push(t('record.issue_line', { line: lineLabelById(ctx, p.id) }));
    for (const p of (v.ytd && v.ytd.problems) || []) issues.push(t('record.issue_ytd', { line: lineLabelById(ctx, p.lineId) }));
    for (const p of (v.time && v.time.problems) || []) issues.push(t('record.issue_time', { line: lineLabelById(ctx, p.lineId) }));
    for (const p of (v.leave && v.leave.problems) || []) issues.push(t('record.issue_leave', { type: content.leaveType(p.type).label }));
    for (const b of v.bridges || []) issues.push(t('record.issue_bridge', { period: ctx.fmt.period(b.period) }));
    if (v.paymentOk === false) issues.push(t('record.issue_payment'));
    if (!v.ok && !issues.length) issues.push(t('record.issue_other'));
  }
  const ok = Boolean(v && v.ok && !issues.length);
  return [
    h('div', { class: 'pl-ra-status' }, h('span', { class: ['pl-chip', ok ? 'pl-chip-positive' : 'pl-chip-negative'], dataset: { consistency: ok ? 'ok' : 'problem' } }, icon(ok ? 'check' : 'warn', { size: 12 }), t(ok ? 'record.consistency_chip_ok' : 'record.consistency_chip_problem'))),
    ok ? h('p', { class: 'small' }, t('record.consistency_ok')) : [
      h('p', { class: 'small strong' }, t('record.consistency_problems', { count: issues.length })),
      h('ul', { class: 'pl-ra-issues' }, issues.map((i) => h('li', null, i))),
    ],
    h('p', { class: 'muted xs' }, t('record.consistency_note')),
  ];
}

