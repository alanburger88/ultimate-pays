function lineCard(ctx, line, sel) {
  const t = ctx.t;
  const hours = hoursText(ctx, line);
  const rate = rateText(ctx, line);
  const label = ctx.content.lineLabel(line);
  const statutory = line.statutoryKey ? ctx.content.statutory(line.statutoryKey) : null;
  return h('article', { class: ['pl-line-card pl-ra-linecard', sel && 'is-selected'], dataset: { lineId: line.id, category: line.category } },
    h('div', { class: 'sel' }, selectBox(ctx, line, sel)),
    h('div', { class: 'body' },
      h('span', { class: 'title' }, label),
      statutory && statutory.term !== label ? h('span', { class: 'pl-statutory', lang: statutory.locale }, statutory.term) : null,
      h('span', { class: 'meta' },
        h('span', null, ctx.content.category(line.category)),
        line.group ? h('span', null, ctx.content.group(line.group)) : null,
        hours !== null ? h('span', null, `${t(line.calc && line.calc.type === 'units_rate' ? 'common.units' : 'common.hours')}: ${hours}`) : null,
        rate !== null && !rate.money ? h('span', null, `${t('common.rate')}: ${rate.text}`) : null,
      ),
    ),
    h('div', { class: 'amounts' },
      amount(ctx, line.amountMinor, { cls: 'amt' }),
      h('span', { class: 'ytd' }, `${t('common.ytd_short')} `, typeof line.ytdMinor === 'number' ? amount(ctx, line.ytdMinor) : '—'),
      rate !== null && rate.money ? h('span', { class: 'ytd' }, `${t('common.rate')} `, sensitiveText(ctx, rate.text)) : null,
    ),
    h('div', { class: 'actions' }, openLineButton(ctx, line, { text: true })),
  );
}

function totalsList(ctx) {
  const t = ctx.t;
  const { profile, content, computed } = ctx.doc;
  const primary = profile.primaryTotal;
  const payable = profile.payableTotal || primary;
  const hid = uid('ratot');
  return h('div', { class: 'pl-ra-totals-wrap', role: 'group', aria: { labelledby: hid } },
    h('h4', { id: hid }, t('details.totals_title')),
    h('ul', { class: 'pl-ra-totals' }, profile.totals.map((def) => {
      const isPrimary = def.id === primary;
      const isPayable = def.id === payable && payable !== primary;
      return h('li', { class: [def.prominent && 'is-prominent', isPrimary && 'is-primary', isPayable && 'is-payable'], dataset: { total: def.id } },
        h('span', { class: 'name' }, h('span', null, content.total(def.id)),
          isPrimary ? h('span', { class: 'pl-chip pl-chip-accent' }, t('masthead.net_pay')) : null,
          isPayable ? h('span', { class: 'pl-chip pl-chip-positive' }, t('masthead.amount_paid')) : null),
        amount(ctx, computed.totals[def.id]),
      );
    })),
  );
}

